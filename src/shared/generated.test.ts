import { describe, expect, it } from 'vitest';
import {
  generatedFilesNote,
  generatedInDiff,
  hasGeneratedMarker,
  isGenerated,
  isGeneratedPath,
} from './generated.js';

describe('isGeneratedPath', () => {
  it('tags lockfiles', () => {
    expect(isGeneratedPath('package-lock.json')).toBe(true);
    expect(isGeneratedPath('web/pnpm-lock.yaml')).toBe(true);
    expect(isGeneratedPath('Cargo.lock')).toBe(true);
  });

  it('tags build output directories', () => {
    expect(isGeneratedPath('dist/mac-arm64/main.js')).toBe(true);
    expect(isGeneratedPath('packages/app/build/index.html')).toBe(true);
  });

  it('tags minified bundles, sourcemaps and compiler output', () => {
    expect(isGeneratedPath('static/app.min.js')).toBe(true);
    expect(isGeneratedPath('static/app.js.map')).toBe(true);
    expect(isGeneratedPath('api/service.pb.go')).toBe(true);
    expect(isGeneratedPath('api/service_pb2.py')).toBe(true);
  });

  it('tags snapshots and .generated/.gen names', () => {
    expect(isGeneratedPath('src/__snapshots__/App.test.tsx.snap')).toBe(true);
    expect(isGeneratedPath('src/schema.generated.ts')).toBe(true);
    expect(isGeneratedPath('src/routes.gen.ts')).toBe(true);
  });

  it('leaves hand-written source alone', () => {
    expect(isGeneratedPath('src/api/client.ts')).toBe(false);
    expect(isGeneratedPath('src/main/gitService.ts')).toBe(false);
    expect(isGeneratedPath('README.md')).toBe(false);
    // "out" only counts as a directory segment, not as part of a name
    expect(isGeneratedPath('src/layout/checkout.tsx')).toBe(false);
  });
});

describe('hasGeneratedMarker', () => {
  it('finds a marker in the header', () => {
    expect(hasGeneratedMarker('// @generated by protoc\nexport const x = 1;\n')).toBe(true);
    expect(hasGeneratedMarker('# DO NOT EDIT — regenerate with `make api`\nx = 1\n')).toBe(true);
  });

  it('is case-insensitive', () => {
    expect(hasGeneratedMarker('/* do not edit */\n')).toBe(true);
  });

  it('ignores a marker past the header', () => {
    const body = Array.from({ length: 39 }, (_, i) => `const v${i} = ${i};`).join('\n');
    expect(hasGeneratedMarker(`${body}\n// DO NOT EDIT the block below\n`)).toBe(false);
  });

  it('is false for ordinary source', () => {
    expect(hasGeneratedMarker('export function add(a: number, b: number) {\n  return a + b;\n}\n')).toBe(false);
  });

  it('ignores code that merely mentions the marker', () => {
    // this module's own header would otherwise tag itself
    expect(hasGeneratedMarker("const MARKER = /@generated|DO NOT EDIT/i;\n")).toBe(false);
    expect(hasGeneratedMarker('if (text.includes("DO NOT EDIT")) skip();\n')).toBe(false);
  });

  it('handles the common comment syntaxes', () => {
    expect(hasGeneratedMarker('# @generated\n')).toBe(true);
    expect(hasGeneratedMarker('-- @generated by sqlc\n')).toBe(true);
    expect(hasGeneratedMarker('<!-- @generated -->\n')).toBe(true);
    expect(hasGeneratedMarker('#!/usr/bin/env python\n"""@generated"""\n')).toBe(true);
    expect(hasGeneratedMarker(' * Code generated by protoc. DO NOT EDIT.\n')).toBe(true);
  });
});

describe('isGenerated', () => {
  it('takes either signal', () => {
    expect(isGenerated('package-lock.json')).toBe(true);
    expect(isGenerated('src/schema.ts', '// @generated\n')).toBe(true);
    expect(isGenerated('src/schema.ts', 'export type X = 1;\n')).toBe(false);
    expect(isGenerated('src/schema.ts')).toBe(false);
  });
});

describe('generatedInDiff', () => {
  it('picks generated paths out of a diff', () => {
    const diff = [
      'diff --git a/src/app.ts b/src/app.ts',
      'index 111..222 100644',
      '--- a/src/app.ts',
      '+++ b/src/app.ts',
      '@@ -10,2 +10,3 @@ function go() {',
      '   const x = 1;',
      '+  const y = 2;',
      'diff --git a/package-lock.json b/package-lock.json',
      '--- a/package-lock.json',
      '+++ b/package-lock.json',
      '@@ -5,1 +5,2 @@',
      '+    "resolved": "…",',
    ].join('\n');
    expect(generatedInDiff(diff)).toEqual(['package-lock.json']);
  });

  it('reads a marker from a hunk that starts at line 1', () => {
    const diff = [
      'diff --git a/src/schema.ts b/src/schema.ts',
      'new file mode 100644',
      '--- /dev/null',
      '+++ b/src/schema.ts',
      '@@ -0,0 +1,3 @@',
      '+// @generated by codegen — do not edit',
      '+export type X = 1;',
    ].join('\n');
    expect(generatedInDiff(diff)).toEqual(['src/schema.ts']);
  });

  it('ignores a marker in a hunk further down the file', () => {
    const diff = [
      'diff --git a/src/app.ts b/src/app.ts',
      '--- a/src/app.ts',
      '+++ b/src/app.ts',
      '@@ -80,1 +80,2 @@',
      '+// DO NOT EDIT the table below by hand',
    ].join('\n');
    expect(generatedInDiff(diff)).toEqual([]);
  });

  it('skips deleted files', () => {
    const diff = [
      'diff --git a/src/old.ts b/src/old.ts',
      '--- a/src/old.ts',
      '+++ /dev/null',
      '@@ -1,2 +0,0 @@',
      '-// @generated',
    ].join('\n');
    expect(generatedInDiff(diff)).toEqual([]);
  });
});

describe('generatedFilesNote', () => {
  it('is empty when nothing is generated', () => {
    expect(generatedFilesNote('+++ b/src/app.ts\n@@ -1,1 +1,2 @@\n+const x = 1;\n')).toBe('');
  });

  it('lists the generated paths', () => {
    const note = generatedFilesNote('+++ b/dist/bundle.js\n@@ -1,1 +1,2 @@\n+x\n');
    expect(note).toContain('do NOT report findings inside them');
    expect(note).toContain('- dist/bundle.js');
  });
});
